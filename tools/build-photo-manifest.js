/* Lists the photos inside each date folder (assets/photos/dates/<folder>/)
   and writes js/photo-manifest.js, because a static website can't list
   folders by itself.

   Runs automatically on Vercel/Netlify deploys (see vercel.json / netlify.toml).
   To run it by hand:   node tools/build-photo-manifest.js                    */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const datesDir = path.join(root, "assets/photos/dates");
const out = path.join(root, "js/photo-manifest.js");
const IMG = /\.(jpe?g|png|webp|gif|avif)$/i;
const natural = new Intl.Collator(undefined, { numeric: true, sensitivity: "base" }).compare;

const dates = {};
if (fs.existsSync(datesDir)) {
  fs.readdirSync(datesDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .sort((a, b) => natural(a.name, b.name))
    .forEach((d) => {
      const files = fs.readdirSync(path.join(datesDir, d.name)).filter((f) => IMG.test(f) && !f.startsWith(".")).sort(natural);
      if (files.length) dates[d.name] = files;
    });
}

fs.writeFileSync(
  out,
  "/* Generated by tools/build-photo-manifest.js — don't edit by hand. */\n" +
    "window.PHOTO_MANIFEST = " + JSON.stringify({ dates: dates }, null, 2) + ";\n"
);
const n = Object.values(dates).reduce((a, f) => a + f.length, 0);
console.log("photo-manifest: " + n + " photo(s) in " + Object.keys(dates).length + " date folder(s)");
